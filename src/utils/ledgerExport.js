const fmtNumber = (n) => Number(n || 0).toFixed(2);

const fmtDate = (d) => (d ? new Date(d).toLocaleDateString('en-IN') : '-');

const csvEscape = (value) => {
  const str = String(value ?? '');
  if (/[",\n]/.test(str)) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
};

// Builds a CSV (Export Excel) file of the current Ledger Statement view and
// triggers a browser download - no backend endpoint needed, data is already
// loaded on the page.
export const downloadLedgerCsv = (statement) => {
  const {
    statementId, ledger, financialYear, fromDate, toDate, currency,
    openingBalance, openingDate, openingBalanceType,
    transactions, totalDebit, totalCredit, closingBalance, closingBalanceType,
    generatedBy, generatedDate
  } = statement;

  const rows = [];

  rows.push([`Ledger Statement - ${ledger?.ledgerName || ''}`]);
  rows.push(['Statement ID', statementId || '-']);
  rows.push(['Ledger Code', ledger?.ledgerCode || '-']);
  rows.push(['Account Type', ledger?.accountType || '-']);
  rows.push(['Financial Year', financialYear || '-']);
  rows.push(['From Date', fmtDate(fromDate)]);
  rows.push(['To Date', fmtDate(toDate)]);
  rows.push(['Currency', currency || 'INR']);
  rows.push([]);
  rows.push(['Opening Date', fmtDate(openingDate)]);
  rows.push(['Opening Balance', fmtNumber(openingBalance), openingBalanceType || '']);
  rows.push([]);
  rows.push(['Date', 'Voucher #', 'Voucher Type', 'Reference #', 'Description', 'Debit', 'Credit', 'Running Balance']);

  (transactions || []).forEach((row) => {
    rows.push([
      fmtDate(row.date),
      row.voucherNumber || '-',
      row.voucherType || '-',
      row.referenceNumber || '-',
      row.description || '-',
      fmtNumber(row.debit),
      fmtNumber(row.credit),
      fmtNumber(row.balance)
    ]);
  });

  rows.push([]);
  rows.push(['Total Debit', fmtNumber(totalDebit)]);
  rows.push(['Total Credit', fmtNumber(totalCredit)]);
  rows.push(['Closing Balance', fmtNumber(closingBalance), closingBalanceType || '']);
  rows.push([]);
  rows.push(['Generated By', generatedBy || '-']);
  rows.push(['Generated Date', generatedDate ? new Date(generatedDate).toLocaleString('en-IN') : '-']);

  const csvContent = rows.map((row) => row.map(csvEscape).join(',')).join('\r\n');
  const blob = new Blob(['\ufeff' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);

  const link = document.createElement('a');
  link.href = url;
  const safeName = (ledger?.ledgerName || 'ledger').replace(/[^a-z0-9]+/gi, '_').toLowerCase();
  link.download = `ledger_statement_${safeName}.csv`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};
